/** n croches répétées d'un accord de main gauche ; doigté déduit des écarts (5-4-1, 5-3-1, 5-2-1, 5-3-2-1). */
function lhRep(notes: string, n: number, d = e, mk?: string): Tok[] {
  const ms = notes.split("+").map(M);
  const g1 = ms.length > 1 ? ms[1] - ms[0] : 0;
  const f = ms.length === 1 ? "5" : ms.length === 2 ? (ms[1] - ms[0] >= 5 ? "51" : "52") : ms.length === 4 ? "5321" : g1 <= 2 ? "541" : g1 <= 4 ? "531" : "521";
  return Array.from({ length: n }, (_, i): Tok => (i === 0 && mk ? [notes, d, f, mk] : [notes, d, f]));
}
const L = (...parts: [string, number, string?][]): Tok[] => parts.flatMap(([n, k, mk]) => lhRep(n, k, e, mk));

